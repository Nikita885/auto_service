"""Кто пришёл: IP клиента за обратным прокси.

Отдельный модуль, потому что ошибиться здесь дорого. `X-Forwarded-For`
начинает писать сам клиент, а nginx только дописывает к нему свой
`$remote_addr`. Значит доверять можно ровно последним N элементам списка,
где N — число собственных прокси перед приложением. Если брать первый,
как это делают почти все примеры в интернете, весь заголовок оказывается
под контролем того, кто шлёт запрос: любой лимит по IP обходится сменой
одной строки, а в журнале OTP оседает выдуманный адрес.
"""

from __future__ import annotations

from rest_framework.throttling import BaseThrottle


def client_ip(request) -> str | None:
    """IP клиента с учётом `REST_FRAMEWORK["NUM_PROXIES"]`.

    Берём ту же функцию, по которой DRF считает ключ throttling. Два
    независимых ответа на вопрос «кто это пришёл» рано или поздно
    разъедутся, и разъедутся молча.
    """
    return BaseThrottle().get_ident(request)
