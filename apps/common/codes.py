"""Короткие человекочитаемые коды.

Их называют вслух и диктуют по телефону: код записи на посту, код
приглашения знакомому. Поэтому из алфавита выкинуты «O» и «I» — на слух и
на экране телефона они неотличимы от нуля и единицы, а ошибка в одном
символе означает чужую запись или чужого пригласившего.

Алфавит общий на весь проект: два разных набора символов в двух приложениях
означали бы, что где-то код можно прочитать, а где-то нет.
"""

import secrets
import string

CODE_ALPHABET = string.ascii_uppercase.replace("O", "").replace("I", "") + "23456789"


def generate_code(length: int = 6) -> str:
    """Случайный код заданной длины из безопасного алфавита.

    `secrets`, а не `random`: код приглашения даёт право на начисления, и
    предсказуемый генератор позволил бы подобрать чужой.
    """
    return "".join(secrets.choice(CODE_ALPHABET) for _ in range(length))
