"""Хранилище статики для прода.

Имена файлов получают хеш содержимого (`landing.a1b2c3d4.css`). Без этого
редизайн не доезжает до людей, которые уже открывали сайт: nginx отдаёт
`/static/` с длинным сроком жизни, имя файла не меняется, и браузер честно
показывает старый CSS поверх нового HTML — пока кеш не протухнет. Задним
числом такой кеш не сбросить ничем, кроме смены адреса файла.
"""

from django.contrib.staticfiles.storage import ManifestStaticFilesStorage


class ForgivingManifestStaticFilesStorage(ManifestStaticFilesStorage):
    """То же самое, но без 500-й на незнакомой записи манифеста.

    Штатное хранилище на файле, которого нет в манифесте, бросает исключение —
    и страница падает целиком. `collectstatic` в entrypoint запускается с
    `|| true`, то есть его падение проходит тихо, и цена ошибки оказалась бы
    несоразмерной: вместо устаревшей картинки лёг бы весь сайт.

    С `manifest_strict = False` такой файл отдаётся по имени без хеша. Он лежит
    рядом в `STATIC_ROOT` — `collectstatic` копирует и оригиналы тоже.
    """

    manifest_strict = False
