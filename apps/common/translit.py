"""Приведение строки к виду, в котором её можно искать.

Человек ищет машину как придётся: «мерс», «merc», «Мерседес», «мерседес
бенц», «MERCEDES-BENZ». Всё это должно находить одну и ту же марку. Задача
решается не хитрым поиском, а приведением и запроса, и справочника к одной
форме: латиница, нижний регистр, без разделителей.

Направление выбрано «кириллица → латиница», а не наоборот: у латиницы нет
мягкого знака и шипящих, обратное преобразование неоднозначно («ш» → «sh»,
но «sh» — это и «ш», и «с» + «х»).

Своя таблица, а не библиотека: это сорок строк, а зависимость в образе
стоит обновлений и уязвимостей. Правила транслитерации здесь не
паспортные, а поисковые — важно, чтобы одинаково звучащее совпадало, а не
чтобы результат годился для документов.
"""

from __future__ import annotations

_CYRILLIC_TO_LATIN = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}

# Латиница сводится к «как это слышно по-русски». Каждая пара появилась из
# реального промаха поиска:
#   x → ks   Lexus и «Лексус»
#   w → v    Volkswagen и «Фольксваген»
#   q → k    Qashqai и «Кашкай»
#   j → i    Jetta и «Джетта»
#   c → k    Camry и «Камри» (латинская «c» читается то как «к», то как «с»,
#            и к «к» её сводить выгоднее: «ц» в таблице выше даёт ту же «c»)
#   y → i    Camry и «Камри», Toyota и «Тойота»
# Правило применяется и к уже транслитерированной кириллице — иначе два
# написания одного слова расходились бы на последнем шаге.
_LATIN_FOLDING = {
    "x": "ks", "w": "v", "q": "k", "j": "i", "c": "k", "y": "i",
}


def translit(value: str) -> str:
    """Кириллица в латиницу, посимвольно. Остальное остаётся как есть."""
    return "".join(_CYRILLIC_TO_LATIN.get(char, char) for char in value)


def normalize(value: str) -> str:
    """Форма для сравнения: латиница, нижний регистр, только буквы и цифры.

    Разделители выбрасываются целиком, а не заменяются пробелом: «E-Class»,
    «E Class» и «eclass» — это одно и то же, и запрос «эклас» обязан
    находить их все.
    """
    lowered = translit(value.casefold())
    folded = "".join(_LATIN_FOLDING.get(char, char) for char in lowered)
    return "".join(char for char in folded if char.isalnum())


def search_index(*parts: str) -> str:
    """Строка для поиска по нескольким источникам сразу.

    Части разделяются пробелом, а не склеиваются подряд: иначе конец
    одного слова и начало другого дали бы ложное совпадение — «Kia» плюс
    «Rio» нашлись бы по запросу «ари».

    Каждая часть попадает в индекс дважды: целиком без разделителей и по
    словам. «Mercedes-Benz» даёт и `mercedesbenz`, и `mercedes benz` —
    первое находится запросом «mercedesbenz», второе позволяет набрать
    «мерседес бенц» двумя словами. Без обеих форм одна из них не
    находилась бы, а какую наберёт человек, заранее неизвестно.
    """
    chunks: list[str] = []
    for part in parts:
        glued = normalize(part)
        if not glued:
            continue
        chunks.append(glued)
        words = [word for raw in _split(part) if (word := normalize(raw))]
        if len(words) > 1:
            chunks.extend(words)
    # Порядок сохраняем, дубли убираем: индекс участвует в сравнении
    # `startswith`, и первым обязано стоять каноническое имя.
    return " ".join(dict.fromkeys(chunks))


def _split(value: str) -> list[str]:
    """Разбить по всему, что не буква и не цифра."""
    word: list[str] = []
    words: list[str] = []
    for char in value:
        if char.isalnum():
            word.append(char)
        elif word:
            words.append("".join(word))
            word = []
    if word:
        words.append("".join(word))
    return words
