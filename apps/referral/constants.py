from django.db import models


class MatrixPosition(models.TextChoices):
    """Место под родителем в матрице. Ширина матрицы = число вариантов."""

    LEFT = "left", "левое"
    RIGHT = "right", "правое"


class PointsKind(models.TextChoices):
    """Что за движение баллов. Журнал — единственный источник правды."""

    # Начисления «сразу три линии вверх» — прежняя схема. Новые не
    # создаются, но старые строки журнала остаются: это чьи-то баллы.
    ACCRUAL = "accrual", "начисление"
    # Ежедневная выплата по бинарной схеме — меньшее плечо (или оба, если
    # равны). Одна строка на участника за сутки.
    PAYOUT = "payout", "выплата"
    SPEND = "spend", "списание"
    ADJUSTMENT = "adjustment", "корректировка"
